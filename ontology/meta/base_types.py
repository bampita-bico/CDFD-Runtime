from ontology.meta.entity import Entity

class State(Entity):
    """Represents a discrete condition or mode of a system."""
    pass

class Memory(Entity):
    """Represents historical context or accumulated structural stress."""
    pass

class Signal(Entity):
    """Represents an active transmission of flow or information."""
    pass

class Risk(Entity):
    """Represents a potential for constraint increase or flow interruption."""
    pass

class Regime(Entity):
    """Represents an overarching set of rules modifying graph propagation."""
    pass

class Agent(Entity):
    """Represents an active participant generating flows or decisions."""
    pass

class Resource(Entity):
    """Represents a reservoir of flow capacity."""
    pass

class Environment(Entity):
    """Represents the global constraint and flow boundaries."""
    pass

class Outcome(Entity):
    """Represents a terminal or measured state of the system."""
    pass
